create or replace function public.rjtech_is_admin()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select coalesce(
    (auth.jwt() -> 'app_metadata' ->> 'rjtech_role') = 'admin',
    false
  );
$$;

revoke all on function public.rjtech_is_admin() from public;
grant execute on function public.rjtech_is_admin() to anon, authenticated;

create table if not exists public.rjtech_products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null,
  category text not null check (category in (
    'celulares','notebooks','macbooks','videojuego','televisores','gadgets','audio'
  )),
  price numeric(12,0) not null check (price >= 0),
  old_price numeric(12,0) check (old_price is null or old_price >= 0),
  stock integer not null default 0 check (stock >= 0),
  rating numeric(3,1) not null default 4.5 check (rating >= 0 and rating <= 5),
  reviews integer not null default 0 check (reviews >= 0),
  installments text not null default '',
  description text not null default '',
  tags text[] not null default '{}',
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

