);

create table if not exists public.rjtech_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.rjtech_orders (id) on delete cascade,
  product_id bigint references public.rjtech_products (id) on delete set null,
  name text not null,
  qty integer not null check (qty > 0),
  unit_price numeric(12,0) not null,
  line_total numeric(12,0) not null
