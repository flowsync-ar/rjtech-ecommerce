create or replace function public.rjtech_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.rjtech_profiles (id, name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    coalesce(new.email, '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists rjtech_on_auth_user_created on auth.users;
create trigger rjtech_on_auth_user_created
  after insert on auth.users
  for each row execute function public.rjtech_handle_new_user();

revoke all on function public.rjtech_handle_new_user() from public, anon, authenticated;

